POEM_ANSWERS = {norm_text(k): v for k, v in POEM_PAIRS.items()}


def answer_for(question):
    """上一句 → 下一句；未收录返回 None（精确优先，再按相似度模糊）。

    模糊阈值见 MATCH_RATIO：5/7 言句容忍 1 个 OCR 误读字；未命中交
    调用方随机兜底（300环 千古一题，用户 2026-11-27 规则）。
    """
    q = norm_text(question)
    if not q:
        return None
    ans = POEM_ANSWERS.get(q)
    if ans:
        return ans
    best, best_ratio = None, 0.0
    for key, val in POEM_ANSWERS.items():
        ratio = difflib.SequenceMatcher(None, q, key).ratio()
        if ratio > best_ratio:
            best, best_ratio = val, ratio
    return best if best_ratio >= MATCH_RATIO else None
